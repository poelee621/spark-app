  generateArticle(style, topic) {
    const t = (topic || '').trim() || '这件事';
    const S = this.ARTICLE[style] || this.ARTICLE.practical;
    const info = this.analyzeTopic(t);
    const titles = this.makeTitles(style, t, info);
    const intro = pick(S.intro) + '\n\n';
    const sections = S.sec.map(sec => {
      const para = sec.p.map(arr => arr.join('')).map(s => s.replace(/\$\{t\}/g, t)).join('');
      return { h: sec.h(t), p: para };
    });
    const outro = pick(S.outro).replace(/\$\{t\}/g, t);
    const golden = pick(S.golden);
    let md = '> ' + pick(this.HOOK[style] || S.intro[0]) + '\n\n';
    sections.forEach(s => { md += '## ' + s.h + '\n\n' + s.p + '\n\n'; });
    md += outro + '\n\n---\n\n**金句：** ' + golden;
    return { topic: t, titles, sections, intro, outro, golden, md };
  }
